/* Node regression tests for isolated V3 basic-turn practice. */
'use strict';
const assert=require('node:assert/strict');
const A=require('../v3/battle-actions.js');
const P=require('../v3/turn-practice.js');
let state=P.fresh();
assert.equal(state.round,1);
assert.equal(state.phase,'start');
assert.equal(state.player.legends.filter(x=>x.ready).length,1,'First player starts with two spent Legends');
assert.equal(P.draw(state).ok,false,'Cannot draw before ready');
let r=P.ready(state);assert(r.ok);state=r.state;
assert.equal(P.roll(state,4,2).ok,false,'Cannot roll before draw');
r=P.draw(state);assert(r.ok);state=r.state;
assert.equal(P.roll(state,20,7).ok,false,'d20 must be last');
r=P.roll(state,4,2);assert(r.ok);state=r.state;
assert.equal(state.phase,'main');assert.equal(state.player.gigs.length,1);
assert.equal(P.play(state,'practice-unit',[{kind:'eddie',id:'opening-eddie'}]).ok,false,'Cannot underpay');
r=P.sell(state,'practice-sell');assert(r.ok);state=r.state;
assert.equal(P.sell(state,'practice-sell-0').ok,false,'Only one sell action per turn');
r=P.play(state,'practice-unit',[{kind:'eddie',id:'opening-eddie'},{kind:'eddie',id:'eddie-practice-sell'}]);assert(r.ok);state=r.state;
assert.equal(state.player.units.length,1);assert.equal(state.player.units[0].lag,true);
assert(state.player.eddies.every(c=>!c.ready));
r=P.pass(state);assert(r.ok);state=r.state;
assert.equal(P.sell(state,'practice-sell-0').ok,false,'Cannot sell in paused opponent turn');
r=P.next(state);assert(r.ok);state=r.state;
assert.equal(state.round,2);assert.equal(state.phase,'start');assert(!state.player.soldThisTurn);
r=P.ready(state);assert(r.ok);state=r.state;
assert(state.player.units[0].ready&&!state.player.units[0].lag,'Next turn: unit readied and Lag cleared');
assert(state.player.eddies.every(c=>c.ready),'Next turn: Eddies restored');
assert(state.player.legends.every(c=>c.ready),'Two first-turn spent legends now ready');
r=P.draw(state);assert(r.ok);state=r.state;
assert.equal(P.roll(state,20,1).ok,false);
r=P.roll(state,6,3);assert(r.ok);assert.equal(r.state.player.gigs.length,2);
assert.equal(P.ready(r.state).ok,false,'Cannot ready during main phase');
console.log('PASS V3 practice: setup, draw, roll, sell, pay, deploy, turn passing, next start and invalid actions.');
